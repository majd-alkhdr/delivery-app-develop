<?php

namespace App\Support;

/**
 * تطبيع النصوص العربية لمطابقة أسماء الزبائن والمناطق.
 * مثال: "أرنبة" و"ارنبة" تُطبَّعان إلى القيمة نفسها.
 */
class ArabicNormalizer
{
    public static function normalize(?string $text): string
    {
        if ($text === null) {
            return '';
        }

        $text = (string) $text;

        // علامات الاتجاه والمحارف غير المرئية
        $text = preg_replace('/[\x{200B}-\x{200F}\x{202A}-\x{202E}\x{2066}-\x{2069}\x{FEFF}\x{061C}]/u', '', $text);

        // التشكيل والتطويل
        $text = preg_replace('/[\x{0610}-\x{061A}\x{064B}-\x{065F}\x{0670}\x{06D6}-\x{06ED}\x{0640}]/u', '', $text);

        // توحيد الحروف
        $text = strtr($text, [
            'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
            'ى' => 'ي',
            'ة' => 'ه',
        ]);

        // الأرقام العربية-الهندية والفارسية إلى لاتينية
        $text = strtr($text, [
            '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
            '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
            '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
            '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        ]);

        // توحيد الشرطات: - ـ – — ‒ ― −
        $text = preg_replace('/[\x{2010}-\x{2015}\x{2212}\x{FE58}\x{FE63}\x{FF0D}_]/u', '-', $text);

        // طيّ المسافات (بما فيها المسافة غير المنقسمة) ثم المسافات حول الشرطات
        $text = preg_replace('/[\s\x{00A0}]+/u', ' ', $text);
        $text = preg_replace('/\s*-\s*/u', ' - ', $text);

        return trim(mb_strtolower($text, 'UTF-8'));
    }
}
